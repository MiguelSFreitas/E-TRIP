function buscarPostosPorCidade($cidade, $postos) {
    return array_values(array_filter($postos, fn($p) => $p['cidade'] === $cidade));
}


function buscarPostoPorId($postoId, $postos) {
    foreach ($postos as $p) {
        if ($p['id'] == $postoId) {
            return $p;
        }
    }
    return null;
}